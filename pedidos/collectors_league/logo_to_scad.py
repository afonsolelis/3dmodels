"""Turn logo.png into logo_engrave.scad: a 2D module logo_2d(d) made of
rectangles, d = logo diameter in mm.

The bright parts of the logo (gold ring, letters, white of the ball) become
the shape to engrave; the dark purple/black parts stay as wall surface.

    python -I logo_to_scad.py   (run from this folder)
"""
import os
from PIL import Image, ImageFilter
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
THRESHOLD = 100      # luminance 0-255; brighter than this gets engraved
GRID = 400           # output pixels across the logo (80 mm -> 0.2 mm/px)

im = Image.open(os.path.join(HERE, "logo.png")).convert("L")
im = im.filter(ImageFilter.MedianFilter(5))            # kill shading noise
# crop to the outer ring (the logo is a centred circle)
a = np.asarray(im)
cols = np.where((a > THRESHOLD).any(axis=0))[0]
rows = np.where((a > THRESHOLD).any(axis=1))[0]
im = im.crop((cols[0], rows[0], cols[-1] + 1, rows[-1] + 1))
size = max(im.size)
sq = Image.new("L", (size, size), 0)
sq.paste(im, ((size - im.size[0]) // 2, (size - im.size[1]) // 2))
small = sq.resize((GRID, GRID), Image.BOX)
m = Image.fromarray(((np.asarray(small) > THRESHOLD) * 255).astype(np.uint8))
# remove 1-px specks and fill 1-px pinholes
m = m.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.MaxFilter(3))
m = m.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3))
m.save(os.path.join(HERE, "logo_engrave_preview.png"))
b = np.asarray(m) > 127

# horizontal runs per row, then stack identical runs of consecutive rows
open_runs = {}   # (x, n) -> (y0, height)
rects = []
for y in range(GRID):
    row = b[GRID - 1 - y]          # flip: image rows go down, OpenSCAD y goes up
    runs = set()
    x = 0
    while x < GRID:
        if row[x]:
            x0 = x
            while x < GRID and row[x]:
                x += 1
            runs.add((x0, x - x0))
        else:
            x += 1
    for k in list(open_runs):
        if k not in runs:
            y0, hgt = open_runs.pop(k)
            rects.append((k[0], y0, k[1], hgt))
    for k in runs:
        if k in open_runs:
            open_runs[k] = (open_runs[k][0], open_runs[k][1] + 1)
        else:
            open_runs[k] = (y, 1)
for k, (y0, hgt) in open_runs.items():
    rects.append((k[0], y0, k[1], hgt))

with open(os.path.join(HERE, "logo_engrave.scad"), "w", newline="\n") as f:
    f.write("// Generated by logo_to_scad.py from logo.png - do not edit by hand.\n")
    f.write(f"// {GRID} x {GRID} grid, threshold {THRESHOLD}, {len(rects)} rectangles.\n")
    f.write(f"logo_grid = {GRID};\n")
    f.write("logo_rects = [\n")
    f.write(",\n".join(f"[{x},{y},{n},{hh}]" for x, y, n, hh in rects))
    f.write("\n];\n")
    f.write("// Logo centred on the origin, d mm across.\n")
    f.write("module logo_2d(d) {\n")
    f.write("    s = d / logo_grid;\n")
    f.write("    scale([s, s]) translate([-logo_grid / 2, -logo_grid / 2])\n")
    f.write("        for (r = logo_rects) translate([r[0], r[1]]) square([r[2] + 0.01, r[3] + 0.01]);\n")
    f.write("}\n")
print(len(rects), "rectangles")
